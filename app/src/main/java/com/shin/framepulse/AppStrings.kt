    )

    fun resolveLangCode(pref: String = try { Prefs.appLanguage } catch (_: Throwable) { "auto" }): String {
        if (pref != "auto") return pref
        return when (Locale.getDefault().language.lowercase(Locale.US)) {
            "id", "in" -> "id"
            "es" -> "es"
            "pt" -> "pt"
            "ja" -> "ja"
            else -> "en"
        }
    }

    fun forLang(pref: String = try { Prefs.appLanguage } catch (_: Throwable) { "auto" }): AppLocaleStrings {
        return when (resolveLangCode(pref)) {
            "id" -> ID
            "es" -> ES
            "pt" -> PT
            "ja" -> JA
            else -> EN
        }
    }

